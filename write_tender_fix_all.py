today = date.today()
updated = 0
deleted = 0

# Дууссан тендерийг устгах
expired = Tender.objects.all()
for t in expired:
    if t.deadline:
        import re
        m = re.search(r'(\d{4}-\d{2}-\d{2})', str(t.deadline))
        if m:
            d = date.fromisoformat(m.group(1))
            if (d - today).days < 0:
                t.delete()
                deleted += 1

print(f"Дууссан тендер устгагдсан: {deleted}")

# Ангилал шинэчлэх
for t in Tender.objects.all():
    text = (t.title + " " + t.method).lower()
    matched = False
    for cat, kws in CATEGORIES.items():
        if any(k in text for k in kws):
            if t.category != cat:
                t.category = cat
                t.save(update_fields=["category"])
                updated += 1
            matched = True
            break
    if not matched and t.category != "other":
        t.category = "other"
        t.save(update_fields=["category"])
        updated += 1

print(f"Ангилал шинэчлэгдсэн: {updated}")
